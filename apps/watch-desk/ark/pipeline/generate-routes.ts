#!/usr/bin/env bun
// Route registry codegen.
//
// Scans src/pages/*.tsx for page modules and writes
// src/route-registry.generated.ts with static imports the bun bundler
// can resolve at build time. Runs as a `bun run build` pre-step (and
// is safe to run anytime; idempotent).
//
// Convention: pages are .tsx files directly in src/pages/. Test files
// (*.test.tsx) and underscore-prefixed special pages (e.g.
// `_placeholder.tsx`) are both included so the registry can apply
// `hideFromNav: true` for them.

import { Glob } from "bun";
import { writeFileSync, existsSync } from "node:fs";
import { join, relative, dirname, basename } from "node:path";

const root = join(process.cwd(), "ui");
const pagesDir = join(root, "src", "pages");
const outFile = join(root, "src", "route-registry.generated.ts");

const header = `// AUTO-GENERATED by scripts/generate-routes.ts — DO NOT EDIT BY HAND.
// Regenerated on each \`bun run build\`. Kept in git so typecheck works
// without a build step. To trigger a refresh: \`bun run codegen:routes\`.

import type { PageModule } from "./route-registry";
`;

if (!existsSync(pagesDir)) {
  // No pages dir yet (fresh scaffold). Emit an empty map so route-registry
  // still compiles and the catch-all _placeholder route handles all paths.
  writeFileSync(outFile, `${header}\nexport const pageModules: Record<string, PageModule> = {};\n`);
  console.log(
    `[codegen:routes] no src/pages/ directory; wrote empty registry to ${relative(root, outFile)}`
  );
  process.exit(0);
}

const glob = new Glob("*.tsx");
const entries: { key: string; importPath: string; identifier: string }[] = [];
for await (const file of glob.scan({ cwd: pagesDir, onlyFiles: true })) {
  if (file.endsWith(".test.tsx")) continue;
  // key matches the legacy `import.meta.glob` output: "./pages/<file>"
  const key = `./pages/${file}`;
  // importPath used in the generated file: "./pages/<basename-without-ext>"
  const importPath = `./pages/${basename(file, ".tsx")}`;
  // identifier needs to be a valid JS identifier — strip leading
  // underscore, replace non-alphanum with underscore.
  const identifier = `Page_${basename(file, ".tsx")
    .replace(/^_/, "Underscore_")
    .replace(/[^A-Za-z0-9]/g, "_")}`;
  entries.push({ key, importPath, identifier });
}
entries.sort((a, b) => a.key.localeCompare(b.key));

const imports = entries
  .map((e) => `import * as ${e.identifier} from "${e.importPath}";`)
  .join("\n");

// `import * as X from "./pages/X"` produces a module-namespace type
// that's structurally assignable to PageModule (default + route fields).
// The Record<string, PageModule> annotation on pageModules is enough to
// type-check each value — no explicit `as PageModule` assertion needed,
// and adding one trips @typescript-eslint/no-unnecessary-type-assertion.
const mapEntries = entries.map((e) => `  ${JSON.stringify(e.key)}: ${e.identifier},`).join("\n");

const body = `${header}
${imports}

export const pageModules: Record<string, PageModule> = {
${mapEntries}
};
`;

writeFileSync(outFile, body);
console.log(`[codegen:routes] wrote ${entries.length} page(s) to ${relative(root, outFile)}`);
