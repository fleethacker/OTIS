import { test, expect } from "@playwright/test";
import { withEphemeralStack } from "../../../ark/pipeline/journey-stack";

test("save private unsent drafts and recover edits across screens", async ({ page }) => {
 const stack = await withEphemeralStack({ fixture: "fixtures/save-unsent-acknowledgement-drafts.json", storyId: "save-unsent-acknowledgement-drafts" });
 try {
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.emulateMedia({ colorScheme: "light" });
  await page.goto(stack.url);
  await page.getByRole("link", { name: "Message records", exact: true }).click();
  const first = page.getByRole("button", { name: /FICTIONAL-DRAFT-001/ });
  const second = page.getByRole("button", { name: /FICTIONAL-DRAFT-002/ });
  await first.click();
  const editor = page.getByRole("textbox", { name: "Acknowledgement text" });
  const save = page.getByRole("button", { name: "Save draft", exact: true });
  const text = "Re: FICTIONAL-DRAFT-001\n  Reviewed revised times.  \nUnsent.";
  await expect(editor).toHaveValue("");
  await editor.fill(text);
  await save.click();
  await expect(page.getByText("Saved · Unsent", { exact: true })).toBeVisible({ timeout: 2000 });
  await page.reload();
  await expect(editor).toHaveValue(text);
  await second.click();
  await expect(editor).toHaveValue("");
  await expect(page.getByText(/Needs review —/)).toBeVisible();
  await editor.fill("Unresolved times — clarification requested, not transmitted.");
  await save.click();
  await expect(page.getByText("Saved · Unsent", { exact: true })).toBeVisible();
  await first.click();
  await expect(editor).toHaveValue(text);
  await editor.fill("dirty text");
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("link", { name: "Calendar", exact: true }).click();
  await expect(editor).toHaveValue("dirty text");
  page.once("dialog", dialog => dialog.dismiss());
  await second.click();
  await expect(editor).toHaveValue("dirty text");
  page.once("dialog", dialog => dialog.accept());
  await second.click();
  await first.click();
  await expect(editor).toHaveValue(text);
  await editor.fill("failed then retried");
  await stack.expectBrowserHTTPError({ path: "/app.v1.DraftService/SaveDraft", status: 503, reason: "Controlled draft save outage" });
  await page.route("**/app.v1.DraftService/SaveDraft", route => route.fulfill({ status: 503, contentType: "application/json", body: '{"code":"unavailable","message":"controlled outage"}' }));
  await save.click();
  await expect(page.getByRole("alert")).toContainText("Save failed");
  await expect(editor).toHaveValue("failed then retried");
  await expect(page.getByText("Saved · Unsent", { exact: true })).toHaveCount(0);
  await page.unroute("**/app.v1.DraftService/SaveDraft");
  await save.click();
  await expect(page.getByText("Saved · Unsent", { exact: true })).toBeVisible();
  let releaseSave!: () => void;
  const heldSave = new Promise<void>(resolve => { releaseSave = resolve; });
  await page.route("**/app.v1.DraftService/SaveDraft", async route => {
    const response = await route.fetch();
    await heldSave;
    await route.fulfill({ response });
  });
  await editor.fill("Submitted text");
  await save.click();
  await editor.fill("Newer edit while saving");
  releaseSave();
  await expect(save).toBeEnabled();
  await expect(editor).toHaveValue("Newer edit while saving");
  await expect(page.getByText("Unsaved changes · Unsent", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Discard changes" }).click();
  await expect(editor).toHaveValue("Submitted text");
  await page.unroute("**/app.v1.DraftService/SaveDraft");
  await stack.screenshot({ page, deliverable: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: "dark" });
  await editor.fill("Mobile draft, still unsent.");
  await save.click();
  await expect(page.getByText("Saved · Unsent", { exact: true })).toBeVisible();
  await page.reload();
  await expect(editor).toHaveValue("Mobile draft, still unsent.");
  await editor.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await stack.screenshot({ page, deliverable: true, name: "journey-mobile-dark" });
  await expect(page.getByRole("button", { name: "Send", exact: true })).toHaveCount(0);
  await stack.expectBrowserHTTPError({ path: "/app.v1.DraftService/ReadDraft", status: 503, reason: "Controlled draft read outage" });
  await page.route("**/app.v1.DraftService/ReadDraft", route => route.fulfill({ status: 503, contentType: "application/json", body: '{"code":"unavailable","message":"controlled outage"}' }));
  await page.reload();
  await expect(page.getByRole("alert")).toContainText("Draft could not be loaded", { timeout: 15000 });
  await expect(editor).toHaveCount(0);
  await page.unroute("**/app.v1.DraftService/ReadDraft");
  await page.getByRole("button", { name: "Retry loading draft" }).click();
  await expect(editor).toHaveValue("Mobile draft, still unsent.");
  await stack.assertNoServerErrors();
 } finally { await stack.teardown(); }
});
