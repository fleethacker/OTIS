#!/usr/bin/env python3
"""Generate ICD DTOs from the locally maintained schema, without network access."""
from pathlib import Path
import argparse
import json
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def generate():
    defs = json.loads((ROOT.parent / "docs/schemas/types.schema.json").read_text())["$defs"]
    names = {name: name[0].upper() + name[1:] for name in defs}
    enums = {}
    out = ["// Generated by backend/tools/generate_types.py; edit the schema/generator, not this file.",
           "use crate::*;", "use serde::{Deserialize, Serialize};", ""]
    time_enum = tuple(defs["activity"]["properties"]["time_status"]["enum"])

    def typ(container, field, spec):
        if "$ref" in spec:
            return names[spec["$ref"].split("/")[-1]]
        if "enum" in spec:
            values = tuple(v for v in spec["enum"] if v is not None)
            name = "TimeStatus" if values == time_enum else names[container] + "".join(x.title() for x in field.split("_"))
            enums[name] = values
            return name
        t = spec.get("type")
        if isinstance(t, list):
            t = next(x for x in t if x != "null")
        if t == "array":
            return f"Vec<{typ(container, field, spec['items'])}>"
        if t == "object":
            return "serde_json::Map<String, serde_json::Value>"
        if spec.get("format") == "date-time":
            return "UtcTimestamp"
        return {"string": "String", "integer": "i64", "number": "f64" if container == "geoPoint" or field == "radius_m" else "f32", "boolean": "bool"}[t]

    for container, schema in defs.items():
        out += ["#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]", "#[serde(deny_unknown_fields)]", f"pub struct {names[container]} {{"]
        for field, spec in schema["properties"].items():
            name = "kind" if field == "type" else field
            required = field in schema["required"]
            nullable = isinstance(spec.get("type"), list) and "null" in spec["type"]
            rust_type = typ(container, field, spec)
            is_array = spec.get("type") == "array"
            optional = nullable or (not required and (not is_array or field == "embedding"))
            if optional:
                rust_type = f"Option<{rust_type}>"
            if field == "type":
                out.append('    #[serde(rename = "type")]')
            if nullable and required:
                out.append('    #[serde(deserialize_with = "crate::required_nullable")]')
            elif not required and is_array and not optional:
                out.append('    #[serde(default, skip_serializing_if = "Vec::is_empty")]')
            elif not required:
                out.append('    #[serde(default, deserialize_with = "crate::optional_present", skip_serializing_if = "Option::is_none")]')
            out.append(f"    pub {name}: {rust_type},")
        out += ["}", f"impl Validate for {names[container]} {{", "    fn validate(&self) -> Result<(), ValidationError> {"]
        for field, spec in schema["properties"].items():
            name = "kind" if field == "type" else field
            expr = f"self.{name}"
            required = field in schema["required"]
            nullable = isinstance(spec.get("type"), list) and "null" in spec["type"]
            optional = nullable or (not required and (spec.get("type") != "array" or field == "embedding"))
            checks = []
            current = "value" if optional else f"&{expr}"
            if "$ref" in spec:
                checks.append(f"{'value' if optional else expr}.validate()?;")
            elif spec.get("type") == "array":
                item = spec["items"]
                c = "value" if optional else f"&{expr}"
                if "$ref" in item:
                    checks.append(f"for item in {c} {{ item.validate()?; }}")
                elif item.get("type") == "string" and item.get("format") != "date-time":
                    checks.append(f'validate_strings({c}, {str(spec.get("uniqueItems", False)).lower()}, "{container}.{field}")?;')
                elif item.get("type") == "number":
                    checks.append(f'if ({c}).is_empty() || ({c}).iter().any(|v| !v.is_finite()) {{ return Err(invalid("{container}.{field}", "finite_nonempty_vector")); }}')
            elif spec.get("minLength") == 1 and "enum" not in spec:
                checks.append(f'nonempty({current}, "{container}.{field}")?;')
            if "pattern" in spec and "format" not in spec:
                pattern = spec["pattern"]
                fn = ("validate_hash_id" if pattern.startswith("^sha256:") else
                      "validate_revision" if pattern.startswith("^[A-Za-z0-9]") else
                      "validate_event_id" if pattern == "^[0-9a-f]{64}$" else
                      "validate_token" if pattern.startswith("^[a-z]") else
                      "validate_time" if field.endswith("time") or field == "time" else None)
                if fn:
                    checks.append(f'{fn}({current}, "{container}.{field}")?;')
                else:
                    prefix = {"period": "v", "frequency": "f", "activity": "a", "contact": "c", "location": "g", "recurrence": "r", "casualty": "q"}.get(container)
                    prefix_arg = "Some(b'a')" if field == "activity_id" else f"Some(b'{prefix}')" if field == "id" and prefix else "None"
                    checks.append(f'validate_subject_id({current}, {prefix_arg}, "{container}.{field}")?;')
            if "minimum" in spec:
                v = "*value" if optional else expr
                checks.append(f'if {v} < {float(spec["minimum"]) if spec.get("type") == "number" else spec["minimum"]} {{ return Err(invalid("{container}.{field}", "minimum")); }}')
            if "maximum" in spec and not (spec["maximum"] == 9223372036854775807):
                v = "*value" if optional else expr
                checks.append(f'if {v} > {float(spec["maximum"]) if spec.get("type") == "number" else spec["maximum"]} {{ return Err(invalid("{container}.{field}", "maximum")); }}')
            if optional and checks:
                out.append(f"        if let Some(value) = &{expr} {{")
                out += ["            " + c for c in checks]
                out.append("        }")
            else:
                out += ["        " + c for c in checks]
        out += ["        self.validate_semantics()", "    }", "}", ""]
    for name, values in enums.items():
        out += ["#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]", f"pub enum {name} {{"]
        for value in values:
            variant = "".join(x.title() for x in re.split(r"[_ ]", value))
            out += [f'    #[serde(rename = "{value}")]', f"    {variant},"]
        out += ["}", ""]
    rustfmt = shutil.which("rustfmt") or str(Path.home() / ".cargo/bin/rustfmt")
    return subprocess.run([rustfmt, "--edition", "2024", "--emit", "stdout"], input="\n".join(out), text=True, capture_output=True, check=True).stdout


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "crates/parse-command-types/src/generated.rs"
    content = generate()
    if args.check:
        if path.read_text() != content:
            raise SystemExit("DTOs differ from the schema: run python3 backend/tools/generate_types.py")
    else:
        path.write_text(content)
