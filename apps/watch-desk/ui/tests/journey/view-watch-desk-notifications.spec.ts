import { test, expect } from "@playwright/test";
import { withEphemeralStack } from "../../../ark/pipeline/journey-stack";

test("source notifications, local reading and UTC reminder", async ({ page }) => {
  const stack = await withEphemeralStack({ fixture: "fixtures/view-watch-desk-notifications.json", storyId: "view-watch-desk-notifications" });
  try {
    await page.clock.setFixedTime(new Date("2026-11-04T23:59:58Z"));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.emulateMedia({ colorScheme: "light" });
    await page.goto(stack.url);
    const bell = page.getByRole("button", { name: "Notifications", exact: true });
    await bell.click();
    const panel = page.getByRole("region", { name: "Notifications", exact: true });
    await expect(panel.getByText("3 unread · In-app only")).toBeVisible();
    await expect(panel.getByText(/Fictional · Illustrative/).first()).toBeVisible();
    await stack.screenshot({ page, deliverable: true });
    await panel.getByRole("button", { name: "Mark as read: Fictional inspection", exact: true }).click();
    await expect(panel.getByText("2 unread · In-app only")).toBeVisible();
    await panel.getByRole("button", { name: "Mark all as read" }).click();
    await expect(panel.getByText("No unread notifications · In-app only")).toBeVisible();
    await page.reload();
    await bell.click();
    await expect(panel.getByText("No unread notifications · In-app only")).toBeVisible();
    await page.clock.setFixedTime(new Date("2026-11-05T00:00:01Z"));
    await expect(panel.getByText("1 unread · In-app only")).toBeVisible();
    await expect(panel.getByRole("link", { name: "Review today's UTC schedule" })).toHaveAttribute("href", /date=2026-11-05/);
    await panel.getByRole("link", { name: "Review today's UTC schedule" }).click();
    await expect(page.getByLabel("UTC date")).toHaveValue("2026-11-05");
    await page.getByLabel("Grid interval").selectOption("30");
    const calendarUrl = new URL(page.url()).pathname + new URL(page.url()).search;
    await bell.click();
    await panel.getByRole("link", { name: /Fictional inspection/ }).click();
    await expect(page.getByRole("article", { name: "Selected message" })).toContainText("FICTIONAL-REVIEW");
    await page.getByRole("link", { name: "Return to Calendar" }).click();
    expect(new URL(page.url()).pathname + new URL(page.url()).search).toBe(calendarUrl);
    await bell.click();
    await page.keyboard.press("Escape");
    await expect(bell).toBeFocused();
    await bell.click();
    await page.getByRole("heading", { name: "Calendar", exact: true }).click();
    await expect(bell).toHaveAttribute("aria-expanded", "false");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ colorScheme: "dark" });
    await bell.click();
    await expect(panel).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await stack.screenshot({ page, deliverable: true, name: "journey-mobile-dark" });
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "Account menu" }).click();
    await expect(page.getByRole("menuitem", { name: "Sign out" })).toBeVisible();
    await page.keyboard.press("Escape");
    await page.route("**/app.v1.SourceDataService/ReadSchedules", route => route.fulfill({ status: 200, contentType: "application/json", body: '{"messages":[]}' }));
    await bell.click();
    await panel.getByRole("button", { name: "Refresh action items" }).click();
    await expect(panel.getByText("No outstanding action items in the returned source data.")).toBeVisible();
    await stack.expectBrowserHTTPError({ path: "/app.v1.SourceDataService/ReadSchedules", status: 503, reason: "Controlled notification refresh outage" });
    await page.route("**/app.v1.SourceDataService/ReadSchedules", route => route.fulfill({ status: 503, contentType: "application/json", body: '{"code":"unavailable","message":"Controlled outage"}' }));
    await panel.getByRole("button", { name: "Refresh action items" }).click();
    await expect(panel.getByRole("alert")).toContainText("Action items unavailable", { timeout: 15000 });
    await expect(panel.getByText("No outstanding action items in the returned source data.")).toHaveCount(0);
    await page.unroute("**/app.v1.SourceDataService/ReadSchedules");
    await panel.getByRole("button", { name: "Retry action items" }).click();
    await expect(panel.getByRole("link", { name: /Fictional inspection/ })).toBeVisible();
    // A controlled identity response proves browser-local isolation without changing auth wiring.
    await page.route("**/app.v1.AppService/GetIdentity", route => route.fulfill({ status: 200, contentType: "application/json", body: '{"username":"second-watchstander","email":"second@example.test"}' }));
    await page.reload();
    await bell.click();
    await expect(panel.getByText("3 unread · In-app only")).toBeVisible();
    await page.unroute("**/app.v1.AppService/GetIdentity");
    await page.reload();
    await bell.click();
    await expect(panel.getByText("No unread notifications · In-app only")).toBeVisible();
    await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error("Controlled storage denial"); }; Storage.prototype.getItem = () => { throw new Error("Controlled storage denial"); }; });
    await page.reload();
    await bell.click();
    await expect(panel.getByText(/Browser storage unavailable/)).toBeVisible();
    await panel.getByRole("button", { name: "Mark all as read" }).click();
    await expect(panel.getByText("No unread notifications · In-app only")).toBeVisible();
    await page.keyboard.press("Escape");
    await page.route("**/logout", route => route.fulfill({ status: 200, contentType: "text/plain", body: "Sign-out destination reached" }));
    await page.getByRole("button", { name: "Account menu" }).click();
    await page.getByRole("menuitem", { name: "Sign out" }).click();
    await expect(page).toHaveURL(/\/logout$/);
    await stack.assertNoServerErrors();
  } finally { await stack.teardown(); }
});
